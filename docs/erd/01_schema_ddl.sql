-- A-03 / #27: 매장 정보. 기존 DB에는 아래 CREATE TABLE을 최초 1회 적용한다.
-- SHOP_ID는 인증/계정 등록 단계에서 할당한 ID이며 자동 생성하지 않는다.
CREATE TABLE SHOP (
    SHOP_ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    ADDRESS VARCHAR2(255 CHAR) NOT NULL,
    ADDRESS_DETAIL VARCHAR2(255 CHAR),
    LATITUDE NUMBER(10, 7) NOT NULL,
    LONGITUDE NUMBER(10, 7) NOT NULL,
    VERSION NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT CK_SHOP_LATITUDE CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_SHOP_LONGITUDE CHECK (LONGITUDE BETWEEN -180 AND 180)
);
