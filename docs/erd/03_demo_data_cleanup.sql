DELETE FROM GRACE_CANCEL_USAGE
WHERE USER_ID BETWEEN 103 AND 140
   OR CANCEL_ID IN (SELECT CANCEL_ID FROM RESERVATION_CANCEL
                    WHERE RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION
                                             WHERE TREATMENT_ID IN (SELECT TREATMENT_ID FROM TREATMENT WHERE SHOP_ID BETWEEN 101 AND 111)
                                                OR USER_ID BETWEEN 103 AND 140));

DELETE FROM NOTIFICATION_DISPATCH
WHERE USER_ID BETWEEN 103 AND 140
   OR EVENT_ID IN (SELECT EVENT_ID FROM NOTIFICATION_EVENT
                   WHERE SHOP_ID BETWEEN 101 AND 111
                      OR RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION WHERE USER_ID BETWEEN 103 AND 140));

DELETE FROM NOTIFICATION_EVENT
WHERE SHOP_ID BETWEEN 101 AND 111
   OR RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION WHERE USER_ID BETWEEN 103 AND 140);

DELETE FROM NOTIFICATION_SUBSCRIPTION
WHERE SHOP_ID BETWEEN 101 AND 111
   OR USER_ID BETWEEN 103 AND 140;

DELETE FROM SETTLEMENT
WHERE SHOP_ID BETWEEN 101 AND 111
   OR DEPOSIT_PAYMENT_ID IN (SELECT DEPOSIT_PAYMENT_ID FROM DEPOSIT_PAYMENT
                             WHERE RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION WHERE USER_ID BETWEEN 103 AND 140));

DELETE FROM RESERVATION_CANCEL
WHERE USER_ID BETWEEN 103 AND 140
   OR RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION
                         WHERE TREATMENT_ID IN (SELECT TREATMENT_ID FROM TREATMENT WHERE SHOP_ID BETWEEN 101 AND 111)
                            OR USER_ID BETWEEN 103 AND 140);

DELETE FROM DEPOSIT_PAYMENT
WHERE RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION
                         WHERE TREATMENT_ID IN (SELECT TREATMENT_ID FROM TREATMENT WHERE SHOP_ID BETWEEN 101 AND 111)
                            OR USER_ID BETWEEN 103 AND 140);

DELETE FROM SHOP_SCHEDULE_EXCEPTION
WHERE SHOP_ID BETWEEN 101 AND 111
   OR RESERVATION_ID IN (SELECT RESERVATION_ID FROM RESERVATION WHERE USER_ID BETWEEN 103 AND 140);

DELETE FROM RESERVATION
WHERE TREATMENT_ID IN (SELECT TREATMENT_ID FROM TREATMENT WHERE SHOP_ID BETWEEN 101 AND 111)
   OR USER_ID BETWEEN 103 AND 140;

DELETE FROM SHOP_CUSTOMER_MEMO
WHERE SHOP_ID BETWEEN 101 AND 111
   OR USER_ID BETWEEN 103 AND 140;

DELETE FROM TREATMENT WHERE SHOP_ID BETWEEN 101 AND 111;
DELETE FROM STAFF WHERE SHOP_ID BETWEEN 101 AND 111;
DELETE FROM SHOP_BUSINESS_HOUR WHERE SHOP_ID BETWEEN 101 AND 111;
DELETE FROM SHOP_TERMS_AGREEMENT WHERE SHOP_ID BETWEEN 101 AND 111;
DELETE FROM SHOP WHERE SHOP_ID BETWEEN 101 AND 111;

DELETE FROM USER_TERMS_AGREEMENT WHERE USER_ID BETWEEN 103 AND 140;
DELETE FROM APP_USER WHERE USER_ID BETWEEN 103 AND 140;
