-- Oracle / H2 공용 읽기 전용 검증. 신규 UNNIE-164 매장만 집계한다.
-- 실패한 검사는 0으로 나눔 오류를 발생시킨다. 데이터를 수정하지 않는다.
SELECT 1 / CASE WHEN COUNT(*) = 50 THEN 1 ELSE 0 END AS CHECK_50_SHOPS
FROM SHOP WHERE LOGIN_ID LIKE 'demo164_s%';

SELECT 1 / CASE WHEN COUNT(DISTINCT REGION_CODE) = 25 THEN 1 ELSE 0 END AS CHECK_25_DISTRICTS
FROM SHOP WHERE LOGIN_ID LIKE 'demo164_s%';

SELECT 1 / CASE WHEN COUNT(*) = 8 THEN 1 ELSE 0 END AS CHECK_8_GANGNAM
FROM SHOP WHERE LOGIN_ID LIKE 'demo164_s%' AND REGION_CODE = '11680';

SELECT 1 / CASE WHEN COUNT(*) = 130 THEN 1 ELSE 0 END AS CHECK_130_NORMAL
FROM TREATMENT T JOIN SHOP S ON S.SHOP_ID = T.SHOP_ID
WHERE S.LOGIN_ID LIKE 'demo164_s%' AND T.TREATMENT_TYPE = 'NORMAL';

SELECT 1 / CASE WHEN COUNT(*) = 20 AND COUNT(DISTINCT T.SHOP_ID) = 16 THEN 1 ELSE 0 END AS CHECK_20_MODELS_16_SHOPS
FROM TREATMENT T JOIN SHOP S ON S.SHOP_ID = T.SHOP_ID
WHERE S.LOGIN_ID LIKE 'demo164_s%' AND T.TREATMENT_TYPE = 'MODEL';

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END AS CHECK_EACH_SHOP_2_NORMAL
FROM SHOP S WHERE S.LOGIN_ID LIKE 'demo164_s%'
AND (SELECT COUNT(*) FROM TREATMENT T WHERE T.SHOP_ID = S.SHOP_ID AND T.TREATMENT_TYPE = 'NORMAL') < 2;

SELECT 1 / CASE WHEN COUNT(*) = 350 THEN 1 ELSE 0 END AS CHECK_350_BUSINESS_HOURS
FROM SHOP_BUSINESS_HOUR H JOIN SHOP S ON S.SHOP_ID = H.SHOP_ID WHERE S.LOGIN_ID LIKE 'demo164_s%';

SELECT 1 / CASE WHEN COUNT(*) = 814 THEN 1 ELSE 0 END AS CHECK_814_OPENINGS
FROM SHOP_SCHEDULE_EXCEPTION E JOIN SHOP S ON S.SHOP_ID = E.SHOP_ID
WHERE S.LOGIN_ID LIKE 'demo164_s%' AND E.EXCEPTION_TYPE = 'OPEN';

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END AS CHECK_OPENING_TIMES
FROM SHOP_SCHEDULE_EXCEPTION E JOIN SHOP S ON S.SHOP_ID = E.SHOP_ID
WHERE S.LOGIN_ID LIKE 'demo164_s%'
AND (E.EXCEPTION_TYPE <> 'OPEN' OR E.STARTS_AT >= E.ENDS_AT
 OR E.STARTS_AT < TIMESTAMP '2026-11-02 00:00:00' OR E.ENDS_AT >= TIMESTAMP '2026-11-21 00:00:00'
 OR EXTRACT(MINUTE FROM E.STARTS_AT) NOT IN (0,30) OR EXTRACT(MINUTE FROM E.ENDS_AT) NOT IN (0,30));

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END AS CHECK_PRICES_AND_DURATIONS
FROM TREATMENT T JOIN SHOP S ON S.SHOP_ID = T.SHOP_ID WHERE S.LOGIN_ID LIKE 'demo164_s%'
AND (T.REGULAR_PRICE <= 0 OR T.PRICE <= 0 OR T.LAST_MINUTE_PRICE <= 0
 OR T.PRICE > T.REGULAR_PRICE OR T.LAST_MINUTE_PRICE > T.PRICE
 OR MOD(T.REGULAR_PRICE, 100) <> 0 OR MOD(T.PRICE, 100) <> 0 OR MOD(T.LAST_MINUTE_PRICE, 100) <> 0
 OR T.DURATION_MINUTES <= 0 OR T.DURATION_MINUTES > 9990 OR MOD(T.DURATION_MINUTES, 30) <> 0);

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END AS CHECK_MODEL_CONDITIONS
FROM TREATMENT T JOIN SHOP S ON S.SHOP_ID = T.SHOP_ID WHERE S.LOGIN_ID LIKE 'demo164_s%'
AND ((T.TREATMENT_TYPE = 'MODEL' AND (T.MODEL_CONDITION IS NULL OR T.PHOTO_NOTICE IS NULL))
 OR (T.TREATMENT_TYPE = 'NORMAL' AND (T.MODEL_CONDITION IS NOT NULL OR T.PHOTO_NOTICE IS NOT NULL)));

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END AS CHECK_SHOP_VALUES
FROM SHOP WHERE LOGIN_ID LIKE 'demo164_s%'
AND (STATUS <> 'ACTIVE' OR CATEGORY_ID NOT IN (1,2,3,4,5) OR LENGTH(REGION_CODE) <> 5
 OR LATITUDE NOT BETWEEN 37.4 AND 37.75 OR LONGITUDE NOT BETWEEN 126.7 AND 127.25
 OR ADDRESS NOT LIKE '서울특별시 %');

SELECT 1 / CASE WHEN COUNT(*) = 0 THEN 1 ELSE 0 END AS CHECK_BUSINESS_HOUR_VALUES
FROM SHOP_BUSINESS_HOUR H JOIN SHOP S ON S.SHOP_ID = H.SHOP_ID WHERE S.LOGIN_ID LIKE 'demo164_s%'
AND (H.DAY_OF_WEEK NOT IN ('MON','TUE','WED','THU','FRI','SAT','SUN') OR H.IS_CLOSED NOT IN ('Y','N')
 OR (H.IS_CLOSED = 'Y' AND (H.OPEN_TIME IS NOT NULL OR H.CLOSE_TIME IS NOT NULL))
 OR (H.IS_CLOSED = 'N' AND (H.OPEN_TIME IS NULL OR H.CLOSE_TIME IS NULL
     OR LENGTH(H.OPEN_TIME) <> 5 OR LENGTH(H.CLOSE_TIME) <> 5 OR H.OPEN_TIME >= H.CLOSE_TIME)));

SELECT REGION_CODE, COUNT(*) AS SHOP_COUNT FROM SHOP WHERE LOGIN_ID LIKE 'demo164_s%' GROUP BY REGION_CODE ORDER BY REGION_CODE;
SELECT S.LOGIN_ID, S.NAME, S.REGION_CODE,
 SUM(CASE WHEN T.TREATMENT_TYPE = 'NORMAL' THEN 1 ELSE 0 END) AS NORMAL_COUNT,
 SUM(CASE WHEN T.TREATMENT_TYPE = 'MODEL' THEN 1 ELSE 0 END) AS MODEL_COUNT
FROM SHOP S JOIN TREATMENT T ON T.SHOP_ID = S.SHOP_ID WHERE S.LOGIN_ID LIKE 'demo164_s%'
GROUP BY S.LOGIN_ID, S.NAME, S.REGION_CODE ORDER BY S.LOGIN_ID;
