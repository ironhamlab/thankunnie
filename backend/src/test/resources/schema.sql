-- 회원·매장 테이블이 아직 없어 FK 제약조건은 제외한다
-- H2 는 NUMBER(19) 를 NUMERIC 으로 인식해 Long(BIGINT) 검증에 실패하므로 ID 컬럼은 BIGINT 로 둔다
-- 테스트 컨텍스트마다 같은 인메모리 DB 에 다시 실행되므로 먼저 지운다
DROP TABLE IF EXISTS NOTIFICATION_SUBSCRIPTION;
DROP SEQUENCE IF EXISTS SEQ_NOTIFICATION_SUBSCRIPTION;

CREATE SEQUENCE SEQ_NOTIFICATION_SUBSCRIPTION START WITH 1 INCREMENT BY 1;

CREATE TABLE NOTIFICATION_SUBSCRIPTION (
    SUBSCRIPTION_ID   BIGINT            NOT NULL,
    USER_ID           BIGINT            NOT NULL,
    SUBSCRIPTION_TYPE VARCHAR2(20 CHAR) NOT NULL,
    SHOP_ID           BIGINT            NOT NULL,
    CATEGORY_NAME     VARCHAR2(20 CHAR),
    REGION_CODE       VARCHAR2(20 CHAR),
    START_TIME        TIMESTAMP(0)      NOT NULL,
    END_TIME          TIMESTAMP(0)      NOT NULL,
    STATUS            VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT        TIMESTAMP         NOT NULL,
    UPDATED_AT        TIMESTAMP         NOT NULL,

    CONSTRAINT PK_NOTIFICATION_SUBSCRIPTION PRIMARY KEY (SUBSCRIPTION_ID),
    CONSTRAINT CK_SUBSCRIPTION_TYPE CHECK (SUBSCRIPTION_TYPE IN ('STORE', 'CATEGORY_REGION')),
    CONSTRAINT CK_SUBSCRIPTION_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_SUBSCRIPTION_TARGET CHECK (
        (SUBSCRIPTION_TYPE = 'STORE'
            AND CATEGORY_NAME IS NULL
            AND REGION_CODE IS NULL)
        OR
        (SUBSCRIPTION_TYPE = 'CATEGORY_REGION'
            AND CATEGORY_NAME IS NOT NULL
            AND REGION_CODE IS NOT NULL)
    ),
    CONSTRAINT CK_SUBSCRIPTION_TIME CHECK (START_TIME < END_TIME)
);
